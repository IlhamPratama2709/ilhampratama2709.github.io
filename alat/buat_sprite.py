for nama, peta in SPRITE.items():
    baris = peta.strip().split("\n")
    im = Image.new("RGBA", (len(baris[0]), len(baris)), (0, 0, 0, 0))
    for y, b in enumerate(baris):
        for x, c in enumerate(b):
            if W[c]:
                im.putpixel((x, y), tuple(int(W[c][i:i + 2], 16) for i in (1, 3, 5)) + (255,))
    im.save(f"images/sprite/{nama}.png", optimize=True)
