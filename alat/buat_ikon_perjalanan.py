for nama, peta in IKON.items():
    baris = peta.strip("\n").split("\n")
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, b in enumerate(baris[:16]):
        for x, c in enumerate(b.ljust(16, ".")[:16]):
            if W[c]:
                im.putpixel((x, y), tuple(int(W[c][i:i + 2], 16) for i in (1, 3, 5)) + (255,))
    im.save(f"images/perjalanan/{nama}.png", optimize=True)
